import math                       # Подключаем математический модуль
print("Формула: T = 2 * pi * sqrt(m / k)")         # формула по условию задачи
pi = 3.14159                                                                   # ЧИСЛО ПИ
m = float(input("Введите массу груза m (кг): "))       # МАСС по условия(0.45)
k = float(input("Введите жесткость пружины k (Н/м): "))   # ЖЕСТКОСТЬ по условия(150)

T = 2 * pi * math.sqrt(m / k)			# Вычисление периода колебаний
print("Результат (Период колебания пружинного маятника):")
print(f"Период колебаний: T = {T:.4f} с")         # вывод на экран вычисления
